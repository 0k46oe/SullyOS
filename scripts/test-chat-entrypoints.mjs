import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const out = 'output/chat-entrypoints';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.QA_BROWSER_PATH ? { executablePath: process.env.QA_BROWSER_PATH } : {}) });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const errors = [];
page.on('pageerror', error => { errors.push(error.message); console.error(error.message); });
await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' || route.request().url().startsWith('data:') ? route.continue() : route.abort());
try {
  await page.goto(`${process.env.SAR_QA_URL || 'http://127.0.0.1:5186'}/test/fixtures/chat-entrypoints.html`, { waitUntil: 'domcontentloaded', timeout: 120000 });
  const avatar = page.getByRole('button', { name: '查看入口测试角色的角色名片', exact: true }).first();
  await avatar.waitFor({ timeout: 120000 });
  await avatar.click();
  await page.getByRole('dialog', { name: '入口测试角色的角色名片', exact: true }).waitFor();
  await page.screenshot({ path: `${out}/profile.png` });
  assert.equal(await page.locator('.sully-chat-extra-action').count(), 0);
  await page.keyboard.press('Escape');
  await page.getByRole('dialog', { name: '入口测试角色的角色名片', exact: true }).waitFor({ state: 'hidden' });
  await page.locator('.sully-chat-inputbar').getByRole('button', { name: '表情', exact: true }).click();
  await page.getByRole('button', { name: '批量管理表情', exact: true }).click();
  const manager = page.getByRole('dialog', { name: '表情管理', exact: true });
  await manager.waitFor();
  await manager.getByRole('button', { name: '测试贴纸', exact: true }).waitFor();
  await page.screenshot({ path: `${out}/stickers.png` });
  await manager.getByRole('button', { name: '返回聊天', exact: true }).click();
  await manager.waitFor({ state: 'hidden' });
  await page.setViewportSize({ width: 320, height: 720 });
  await avatar.click();
  await page.screenshot({ path: `${out}/profile-320.png` });
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '聊天功能', exact: true }).click();
  for (let i = 1; i <= 6; i++) {
    if (await page.getByRole('button', { name: '聊天装扮', exact: true }).isVisible()) break;
    const dot = page.getByRole('button', { name: `第 ${i + 1} 页`, exact: true });
    if (await dot.count()) await dot.click();
  }
  await page.getByRole('button', { name: '聊天装扮', exact: true }).click();
  const wardrobe = page.getByRole('dialog', { name: '给 入口测试角色 换装', exact: true });
  await wardrobe.getByLabel('当前角色', { exact: true }).selectOption('qa-trial-target');
  await wardrobe.getByRole('button', { name: '预览 测试白框', exact: true }).click();
  const detail = page.getByRole('dialog', { name: '测试白框', exact: true });
  await detail.getByRole('button', { name: '试用', exact: true }).click();
  const trial = page.getByRole('dialog', { name: '聊天装扮试用', exact: true });
  await trial.waitFor();
  assert.equal(await page.locator('.sully-chat-header').first().evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(240, 220, 200)');
  const savedCss = () => page.evaluate(async () => { const { DB } = await import('/utils/db.ts'); return (await DB.getCharacter('qa-trial-target'))?.chromeCustomCss || ''; });
  assert.equal(await savedCss(), '');
  await page.locator('.sully-chat-root > [aria-hidden][class*="z-[140]"]').waitFor({ state: 'hidden' });
  await page.screenshot({ path: `${out}/trial.png` });
  await trial.getByRole('button', { name: '返回', exact: true }).click();
  await detail.waitFor();
  assert.equal(await wardrobe.getByLabel('当前角色', { exact: true }).inputValue(), 'qa-trial-target');
  assert.equal(await savedCss(), '');
  await detail.getByRole('button', { name: '试用', exact: true }).click();
  await trial.getByRole('button', { name: '使用', exact: true }).click();
  await trial.waitFor({ state: 'hidden' });
  assert.match(await savedCss(), /240, 220, 200/);
  assert.deepEqual(errors, []);
  console.log('PASS: real Chat avatar and pencil entrypoints; 320px profile; another character trial, return without save, use and persisted CSS');
} catch (error) {
  await page.screenshot({ path: `${out}/failure.png` });
  console.error((await page.locator('body').innerText()).slice(0, 1800));
  throw error;
} finally { await browser.close(); }
