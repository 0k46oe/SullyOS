import fs from 'node:fs';
import path from 'node:path';

// Keep exact utility aliases in sync with the UI sources, including lazy panels.
// No runtime scanning, DOM observers, or Tailwind/CDN dependency is needed.
const sources = ['apps/Character.tsx', 'apps/WorldbookApp.tsx', 'apps/Settings.tsx', 'apps/Appearance.tsx', 'apps/MemoryPalaceApp.tsx', 'components/MemoryGuideActions.tsx'];
for (const dir of ['components/character', 'components/settings', 'components/chat', 'components/os']) {
  sources.push(...fs.readdirSync(dir).filter(name => name.endsWith('.tsx')).map(name => path.join(dir, name)));
}
const families = 'violet|purple|fuchsia|indigo|pink|rose|blue|sky|cyan|emerald|teal|green|lime|amber|yellow|orange';
const utility = new RegExp('(?<![\\w-])((?:(?:hover|active|focus|focus-visible|group-hover|peer-checked):)?(?:bg|text|border|ring|from|via|to|shadow|accent)-(?:' + families + ')-\\d+(?:/\\d+)?)(?![\\w/])', 'g');
const tokens = new Set(sources.flatMap(file => [...fs.readFileSync(file, 'utf8').matchAll(utility)].map(match => match[1])));
const root = 'html[data-paper-ui-style="sage-cream"]';
const scope = ':where([data-paper-ui], [data-paper-ui] *)';
const exclude = ':not(:where([data-paper-ui-exempt], [data-paper-ui-exempt] *))';
const groups = new Map();
const add = (classes, prefix, suffix, rule) => {
  const key = JSON.stringify([prefix, suffix, rule]);
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(classes);
};
const color = (tone, opacity) => opacity === undefined ? 'var(--sp-' + tone + ')' : 'rgba(var(--sp-' + tone + '-rgb), ' + (+opacity / 100) + ')';
for (const token of [...tokens].sort()) {
  const match = token.match(/^(?:(hover|active|focus|focus-visible|group-hover|peer-checked):)?(bg|text|border|ring|from|via|to|shadow|accent)-(\w+)-(\d+)(?:\/(\d+))?$/);
  if (!match) continue;
  const [, state, kind, family, shade, opacity] = match;
  const warm = ['amber', 'yellow', 'orange', 'pink', 'rose'].includes(family);
  const ink = warm ? 'yellow-ink' : 'green-ink';
  let tone = warm ? 'yellow' : 'green-soft';
  if (['text', 'accent'].includes(kind)) tone = ink;
  else if (['border', 'ring'].includes(kind)) tone = warm ? 'yellow' : 'green-line';
  const value = color(tone, kind === 'text' && opacity !== undefined ? Math.max(+opacity, 85) : opacity);
  const escaped = '.' + token.replace(/[:/]/g, '\\$&');
  const prefix = state === 'group-hover' ? '.group:hover ' : state === 'peer-checked' ? '.peer:checked ~ ' : '';
  const suffix = state && !prefix ? ':' + state : '';
  const rules = {
    bg: 'background-color: ' + value + ' !important;',
    text: 'color: ' + value + ' !important;',
    border: 'border-color: ' + value + ' !important;',
    accent: 'accent-color: var(--sp-active) !important;',
    ring: '--tw-ring-color: ' + value + ' !important;',
    shadow: '--tw-shadow-color: rgba(var(--sp-green-line-rgb), .3) !important;',
    from: '--tw-gradient-from: ' + value + ' var(--tw-gradient-from-position) !important; --tw-gradient-to: rgba(var(--sp-green-soft-rgb), 0) var(--tw-gradient-to-position) !important; --tw-gradient-stops: var(--tw-gradient-from), var(--tw-gradient-to) !important;',
    via: '--tw-gradient-stops: var(--tw-gradient-from), ' + value + ' var(--tw-gradient-via-position), var(--tw-gradient-to) !important;',
    to: '--tw-gradient-to: ' + value + ' var(--tw-gradient-to-position) !important;',
  };
  add(escaped, prefix, suffix, rules[kind]);
  if (kind === 'bg' && +shade >= 400) {
    add(escaped, prefix, suffix + ':is(button, a, .text-white, .text-white\\/90)', 'color: var(--sp-' + ink + ') !important;');
    // Full-round tracks need a distinguishable enabled state against the off track.
    add(escaped, prefix, suffix + ':is(.rounded-full:not(button, a), .peer, button[role="switch"][aria-checked="true"], button[aria-pressed="true"].rounded-full)', 'background-color: var(--sp-active) !important;');
  }
}
let output = '/* Generated by scripts/build-paper-ui.mjs. Exact scoped aliases; original utilities stay intact. */\n';
for (const [key, classes] of groups) {
  const [prefix, suffix, rule] = JSON.parse(key);
  output += root + ' ' + prefix + scope + ':is(' + classes.join(', ') + ')' + suffix + exclude + ' { ' + rule + ' }\n\n';
}
fs.writeFileSync('styles/paper-ui-utilities.css', output.trimEnd() + '\n');
